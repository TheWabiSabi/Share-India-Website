// Utility functions for the calculator
export const getIndustryByName = (industryName: string): Industry | undefined => {
  return INDUSTRIES_DATA.find((industry) => industry.industryType === industryName);
};

export const getAvailableInsuranceFeatures = (industry: Industry, categoryKey: string) => {
  const categoryData = industry.insuranceRates[categoryKey as keyof typeof industry.insuranceRates];
  if (!categoryData) return [];

  return (
    Object.entries(categoryData)
      // eslint-disable-next-line @typescript-eslint/no-unused-vars
      .filter(([_, value]) => value !== undefined && value !== undefined)
      .map(([key, value]) => ({
        key,
        value,
        displayName: formatFeatureName(key),
      }))
  );
};

export const formatFeatureName = (featureName: string): string => {
  return featureName
    .replace(/([A-Z])/g, ' $1')
    .replace(/^./, (str) => str.toUpperCase())
    .trim();
};

export const isFeatureAvailable = (
  industry: Industry,
  categoryKey: string,
  featureKey: string,
): boolean => {
  const categoryData = industry.insuranceRates[categoryKey as keyof typeof industry.insuranceRates];
  if (!categoryData) return false;

  const value = categoryData[featureKey as keyof typeof categoryData];
  return value !== undefined && value !== undefined;
};
